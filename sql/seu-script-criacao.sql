CREATE TABLE TRECHO_RODOVIA(
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY ,
    QUILOMETRO_INICIAL NUMBER(10,2) NOT NULL,
    QUILOMETRO_FINAL NUMBER(10,2) NOT NULL ,
    NIVEL_VEGETACAO_CM NUMBER(10,2) NOT NULL,
    TIPO_CLIMA VARCHAR2(20) NOT NULL ,

    CONSTRAINT PK_TRECHO_RODOVIA
        PRIMARY KEY (ID),

    CONSTRAINT CK_TRECHO_KM
        CHECK (QUILOMETRO_FINAL > QUILOMETRO_INICIAL ),

    CONSTRAINT CK_TRECHO_VEGETACAO
        CHECK ( NIVEL_VEGETACAO_CM >= 0 ),

    CONSTRAINT CK_TRECHO_CLIMA
        CHECK ( TIPO_CLIMA IN ('umido' , 'seco'))
);

CREATE TABLE RELATORIO_PRIORIDADE(
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY ,
    QT_PRIORIDADE_ALTA NUMBER NOT NULL ,
    QT_PRIORIDADE_MEDIA NUMBER NOT NULL ,
    QT_SEM_INTERVENCAO NUMBER NOT NULL ,
    RESUMO VARCHAR2(1000) NOT NULL ,
    DATA_GERACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT PK_RELATORIO_PRIORIDADE
        PRIMARY KEY (ID),

    CONSTRAINT CK_RELATORIO_ALTA
        CHECK ( QT_PRIORIDADE_ALTA >= 0 ),

    CONSTRAINT CK_RELATORIO_MEDIA
        CHECK ( QT_PRIORIDADE_MEDIA >=0 ),

    CONSTRAINT CK_RELATORIO_SEM_INTERVENCAO
        CHECK ( QT_SEM_INTERVENCAO >=0 )
);

CREATE INDEX IDX_TRECHO_CLIMA
    ON TRECHO_RODOVIA (TIPO_CLIMA);

CREATE INDEX IDX_RELATORIO_DATA
    ON RELATORIO_PRIORIDADE (DATA_GERACAO);

SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN (
    'TRECHO_RODOVIA',
    'RELATORIO_PRIORIDADE'
)
ORDER BY TABLE_NAME;